// GraphSentinel security console: the live simulated network, its alerts and incidents, monitoring, file scans
// and the audit log. Every value comes from the FastAPI backend (REST) or its /api/sim/ws stream.
import { StrictMode, useEffect, useState } from "react";
import { createRoot } from "react-dom/client";
import { LiveProvider, useLive } from "./live";
import { href, useRoute } from "./router";
import { utcTime } from "./format";
import { Boundary } from "./ui";
import Network from "./pages/Network";
import Alerts from "./pages/Alerts";
import Incidents from "./pages/Incidents";
import Monitoring from "./pages/Monitoring";
import Scan from "./pages/Scan";
import Audit from "./pages/Audit";
import "./console.css";

const PAGES = [
  ["network", "Network", Network], ["alerts", "Alerts", Alerts], ["incidents", "Incidents", Incidents],
  ["monitoring", "Monitoring", Monitoring], ["scan", "File scan", Scan], ["audit", "Audit log", Audit],
];

function SimMarker() {
  const { status, connection } = useLive();
  const st = status?.status;
  return (
    <div className="sim-marker" role="status" aria-live="off">
      <span className="sim-tag">Simulated network</span>
      <span className={`sim-run sim-run--${st || "idle"}`}>{st ? st[0].toUpperCase() + st.slice(1) : "Connecting"}</span>
      <span className="measure sim-clock">{status ? utcTime(status.sim_time) : "—"}</span>
      {connection !== "live" && <span className="sim-conn">{connection === "offline" ? "Stream offline, retrying" : "Connecting stream"}</span>}
    </div>
  );
}

function Badge({ path }) {
  const { status } = useLive();
  if (path !== "incidents" || !status?.open_incidents) return null;
  return <span className="nav-count measure" aria-label={`${status.open_incidents} open`}>{status.open_incidents}</span>;
}

function App() {
  const { path } = useRoute();
  const [menu, setMenu] = useState(false);
  const page = PAGES.find(([p]) => p === path) || PAGES[0];
  const Page = page[2];
  useEffect(() => { document.title = `${page[1]}, GraphSentinel`; setMenu(false); window.scrollTo(0, 0); }, [page]);
  return (
    <>
      <a className="skip" href="#main" onClick={(e) => { e.preventDefault(); document.getElementById("main").focus(); }}>Skip to content</a>
      <header className="topbar">
        <div className="topbar-inner">
          <a className="wordmark" href={href("network")} aria-label="GraphSentinel, network">GraphSentinel</a>
          <nav id="nav" className="nav" data-open={menu} aria-label="Console sections">
            <ul>
              {PAGES.map(([p, label]) => (
                <li key={p}><a href={href(p)} aria-current={p === page[0] ? "page" : undefined}>{label}<Badge path={p} /></a></li>
              ))}
            </ul>
          </nav>
          <SimMarker />
          <button type="button" className="menu-btn" aria-expanded={menu} aria-controls="nav" onClick={() => setMenu((m) => !m)}>
            {menu ? "Close" : "Menu"}
          </button>
        </div>
      </header>
      <main id="main" tabIndex={-1} className="container main">
        <Boundary key={page[0]}><Page /></Boundary>
      </main>
      <footer className="container foot">
        <p>All network traffic in this console is generated by the GraphSentinel simulator. Nothing is captured from or sent to a real network, and nothing is blocked automatically.</p>
      </footer>
    </>
  );
}

createRoot(document.getElementById("root")).render(<StrictMode><LiveProvider><App /></LiveProvider></StrictMode>);
